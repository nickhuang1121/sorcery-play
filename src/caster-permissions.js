// Qualified Spellcaster abilities describe individual permissions. Their union
// does not remove an independent placement prohibition such as Algor's text.
import {unitPrintedAbilityRecord,unitPassiveLayerViews,siteEffectAllowed} from './final-ability-layers.js';
const element=(c,e)=>(c[e]||0)>0||c.elements?.includes(e[0].toUpperCase()+e.slice(1));
const activeRecords=(s,u,A)=>unitPrintedAbilityRecord(s,u,A).records.filter(r=>!u.silenced||r.nature==='gained');
export function casterPermissionViews(s,u,A){
 if(!u||u.dying||A.disabled(u))return [];
 const body=A.card(u.card),result=[];if(body.type==='Avatar')result.push({kind:'any',origin:body.id,characteristic:true});
 if(body.type==='Site'){
  const site=s.board[u.at],d=A.sitePassives[body.slug];if(site&&!site.silenced&&!site.disabled&&d?.siteSpellElements)result.push({kind:'elements',elements:d.siteSpellElements,origin:body.id});
  if(site?.towerMagicTurn===s.turn)result.push({kind:'magic',origin:body.id});return result;
 }
 for(const r of activeRecords(s,u,A)){const p=r.passive||{},origin=r.id;
  if(r.keywords.includes('Spellcaster')&&!p.nonOrdinaryCaster&&!p.excludeCastElements&&!p.spellElement&&!p.spellElements&&!p.siteSpellElements)result.push({kind:'any',origin});
  if(p.nonOrdinaryCaster)result.push({kind:'nonOrdinary',origin});
  if(p.excludeCastElements)result.push({kind:'excludeElements',elements:p.excludeCastElements,origin});
  if(p.spellElement||p.spellElements||p.siteSpellElements)result.push({kind:'elements',elements:p.spellElements||p.siteSpellElements||[p.spellElement],origin});
  if(p.artifactSpellcaster&&!p.excludeCastElements)result.push({kind:'any',origin});
 }
 for(const a of s.artifacts||[])if(a.bearer===u.uid&&!a.silenced&&!a.disabled){const c=A.card(a.card),d=A.equipment?.[c.slug],p=A.passives[c.slug]||{};
  if(d?.spellElement)result.push({kind:'elements',elements:[d.spellElement],origin:a.card});
  if(d?.keywords?.includes('Spellcaster')||p.bearerKeywords?.includes('Spellcaster'))result.push({kind:'any',origin:a.card});
 }
 if(u.mods?.some(m=>m.keyword==='Spellcaster')||u.carryKeywords?.includes('Spellcaster'))result.push({kind:'any',origin:body.id});
 for(const at of A.occupied(u)){const site=s.board[at],d=site&&!site.silenced&&!site.disabled?A.sitePassives[A.card(site.card).slug]:null;if(d?.minionKeywords?.includes('Spellcaster')&&body.type==='Minion'&&siteEffectAllowed(s,u,'modify',A,site.card))result.push({kind:'any',origin:site.card});}
 // Existing explicit grants with no qualified provenance remain generic. A
 // qualified keyword generated by its own passive never grants a second any.
 if(!result.length&&Array.isArray(u.mods)&&A.keywords(u).includes('Spellcaster'))result.push({kind:'any',origin:body.id});
 return result;
}
export function casterPermissionAllows(s,u,c,A,{independent=false}={}){
 if(!u||u.dying||A.disabled(u))return false;if(independent)return true;
 const d=A.definitions[c?.slug]||{};if(d.casters==='any'||d.casterTypes?.some(t=>A.unitTypes(u).includes(t)))return true;
 return casterPermissionViews(s,u,A).some(p=>!c||p.kind==='any'||p.kind==='magic'&&c.type==='Magic'||p.kind==='nonOrdinary'&&c.rarity!=='Ordinary'||p.kind==='elements'&&p.elements.some(e=>element(c,e))||p.kind==='excludeElements'&&!p.elements.some(e=>element(c,e)));
}
export function casterPlacementAllowed(s,u,c,at,A){return c.type!=='Minion'||!unitPassiveLayerViews(s,u,A,'onlySummonHere').some(l=>l.value)||A.occupied(A.unit(s,u.uid)||u).includes(at);}
export function entryHasIndependentCasterPermission(s,h){
 if(h.independentCasterPermission)return true;
 if(h.from?.bound)return !(s.boundSpells||[]).find(v=>v.uid===h.from.bound)?.requiresSpellcaster;
 return !!h.from?.permit&&(s.collectionPermissions||[]).some(p=>p.uid===h.from.permit&&(p.malleus||p.independentCasterPermission));
}
