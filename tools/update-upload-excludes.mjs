// Keep exactly the card-image files used by the runtime index in Git.
// This changes ignore rules only; local alternative printings are never removed.
import fs from 'node:fs';
const root=new URL('../',import.meta.url);
const index=JSON.parse(fs.readFileSync(new URL('data/card-image-index.json',root),'utf8'));
const used=[...new Set(Object.values(index).filter(Boolean).flatMap(row=>[row.front,row.back].filter(Boolean)))].sort();
for(const file of used){
 if(!/^[a-zA-Z0-9_\-]+\.webp$/.test(file))throw Error('Unsupported image filename: '+file);
 if(!fs.existsSync(new URL('card-images/'+file,root)))throw Error('Indexed image missing: '+file);
}
const text=[
 '# Generated by tools/update-upload-excludes.mjs from data/card-image-index.json.',
 '# Ignore unused alternate printings; keep every indexed front/reverse image.',
 '*.webp',...used.map(file=>'!/'+file),''
].join('\n');
const target=new URL('card-images/.gitignore',root);
if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==text)fs.writeFileSync(target,text);
console.log('Card upload rules: '+used.length+' indexed image files retained.');
